//! The Linux provider's answer to the capability catalog for CONTAINERS and
//! pods (`delonix_compute::capability`, ADR-0050) — the kernel is the
//! provider, this adapter is how the engine drives it.
//!
//! Same discipline as the VM backends: an exhaustive `match`, evidence on
//! every `Supported`, and a probe struct so the same declaration renders
//! against an assumed host (the published matrix) and against this machine.

use delonix_compute::capability::{
    Capability as C, CapabilityState as S, HealthStatus, ProviderHealth, ProviderKind,
    ProviderReport,
};
use delonix_compute::capability_host::binary_in_path;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct LinuxHost {
    pub rootless: bool,
    /// Limits reach a cgroup the engine can write (delegated scope, or root).
    pub cgroup_delegated: bool,
    /// `newuidmap`/`newgidmap` present — a rootless user namespace with more
    /// than one uid.
    pub subid_tools: bool,
    /// `nvidia-ctk` present: CDI specs can exist on this host.
    pub nvidia_ctk: bool,
}

impl LinuxHost {
    pub const ASSUMED: LinuxHost = LinuxHost {
        rootless: true,
        cgroup_delegated: true,
        subid_tools: true,
        nvidia_ctk: true,
    };

    /// Reads this machine. The delegation probe creates and removes one empty
    /// cgroup; nothing else has a side effect.
    pub fn probe() -> LinuxHost {
        LinuxHost {
            rootless: super::is_rootless(),
            cgroup_delegated: super::cgroup_limits_apply(),
            subid_tools: binary_in_path("newuidmap") && binary_in_path("newgidmap"),
            nvidia_ctk: binary_in_path("nvidia-ctk"),
        }
    }
}

pub fn report(host: &LinuxHost) -> ProviderReport {
    let (status, reason, message) = if host.rootless && !host.subid_tools {
        (
            HealthStatus::Healthy,
            "SingleUidMapping",
            "newuidmap/newgidmap missing: the user namespace maps one uid only (install uidmap)"
                .to_string(),
        )
    } else if !host.cgroup_delegated {
        (
            HealthStatus::Healthy,
            "CgroupNotDelegated",
            "resource limits are best-effort in this session: run under `systemd-run --user --scope -p Delegate=yes`".to_string(),
        )
    } else {
        (HealthStatus::Healthy, "Ok", String::new())
    };
    let cg = |s: S| s.on_host(host.cgroup_delegated, "no delegated cgroup in this session");
    let gpu = |s: S| {
        s.on_host(
            host.nvidia_ctk,
            "nvidia-ctk not installed: no CDI spec can exist",
        )
    };
    ProviderReport::build(
        "linux",
        ProviderKind::Compute,
        true,
        ProviderHealth {
            status,
            reason,
            message,
        },
        |c| {
            match c {
            C::ProviderAvailability => S::Partial {
                detail: "the kernel is always there; what varies is rootless, subuid and cgroup delegation — each probed separately",
            },
            C::ResourceReadback => S::Supported {
                evidence: "e2e:comandos de leitura (não destrutivos)",
            },
            C::Events => S::Supported {
                evidence: "test:crates/interfaces/delonix-node-api/tests/grpc_watch_events.rs::watch_stream_delivers_an_event_emitted_after_it_opened",
            },
            C::AsyncOperations => S::NotImplemented,
            C::SystemContainerLifecycle
            | C::SystemContainerOciImage
            | C::SystemContainerEntrypointEnv
            | C::SystemContainerExec
            | C::SystemContainerLogs
            | C::SystemContainerExitStatus
            | C::SystemContainerNetworkBridge
            | C::SystemContainerUnprivileged
            | C::SystemContainerSnapshot
            | C::SystemContainerResize
            | C::SystemContainerBackup
            | C::SystemContainerClone
            | C::SystemContainerFirewall
            | C::SystemContainerMove => S::UnsupportedByProvider {
                reason: "application containers run here; a system container, with VM-like semantics, is the Proxmox provider's (ADR-0058)",
            },
            C::ContainerLifecycle => S::Supported {
                evidence: "e2e:container: ciclo de vida + hot reconfig",
            },
            C::ContainerExec => S::Supported {
                evidence: "check:container exec",
            },
            C::ContainerLogs => S::Supported {
                evidence: "check:container logs",
            },
            C::ContainerHotReconfigure => S::Supported {
                evidence: "check:update: mount visível DENTRO do container",
            },
            C::ContainerResourceLimits => cg(S::Supported {
                evidence: "e2e:limites: o que se declara é IMPOSTO, não só escrito",
            }),
            C::ContainerGpuCdi => gpu(S::Partial {
                detail: "consumes CDI specs generated by `nvidia-ctk` (parse+inject proved by unit tests); a live end-to-end run needs a loaded NVIDIA driver — attempted on an RTX 2000 Ada host but the kernel module was unloaded, so `nvidia-ctk cdi generate` and `nvidia-smi` both report `Driver Not Loaded`, and loading it needs root the rootless sandbox denies",
            }),
            C::ContainerSeccompCustomProfile => S::Supported {
                evidence: "check:seccomp: a regra ERRNO continua a negar",
            },
            C::ContainerOomDetection => cg(S::Supported {
                evidence: "chaos:scen_oom",
            }),
            C::PodSharedNetwork => S::Supported {
                evidence: "chaos:scen_pod_namespace_isolation",
            },
            C::PodSharedIpcUts => S::Supported {
                evidence: "chaos:scen_pod_shared_ipc_uts",
            },
            C::PodSharedPid => S::Supported {
                evidence: "chaos:scen_pod_shared_pid",
            },
            C::ContainerImages => S::Supported {
                evidence: "e2e:image",
            },
            C::ContainerBackupRestore => S::Supported {
                evidence: "check:backup restore --force pára, repõe e arranca",
            },
            C::VmCreate
            | C::VmStart
            | C::VmStop
            | C::VmDestroy
            | C::VmRestart
            | C::VmPause
            | C::VmResume
            | C::VmResumeSameIdentity
            | C::VmClone
            | C::VmTemplate
            | C::VmResizeCold
            | C::VmHotplugCpuAdd
            | C::VmHotplugCpuRemove
            | C::VmHotplugMemoryAdd
            | C::VmHotplugMemoryRemove
            | C::VmHotplugDiskAdd
            | C::VmHotplugDiskRemove
            | C::VmHotplugNicAdd
            | C::VmHotplugNicRemove
            | C::VmExtraDisks
            | C::VmExtraNics
            | C::VmDiskResize
            | C::VmPciPassthrough
            | C::VmTpm
            | C::VmCpuModel
            | C::VmCpuPinning
            | C::VmHugepages
            | C::VmCloudInit
            | C::VmRestartPolicyNative
            | C::VmNamespaceIsolation
            | C::VmAntispoof
            | C::VmRawDefinition
            | C::VmNetworkNat
            | C::VmNetworkBridge
            | C::VmNetworkSdn
            | C::VmStaticIp
            | C::StoragePools
            | C::VmSnapshotDisk
            | C::VmSnapshotMemory
            | C::VmSnapshotRestore
            | C::VmSnapshotDelete
            | C::VmSnapshotPersistent
            | C::VmBackupDisk
            | C::VmBackupQuiesced
            | C::VmBackupRestore
            | C::VmMigrationCold
            | C::VmMigrationLive
            | C::VmReplication
            | C::VmHighAvailability
            | C::VmConsoleSerial
            | C::VmConsoleVnc
            | C::VmGuestAgent
            | C::VmIpObserved => S::UnsupportedByProvider {
                reason: "a container provider; VMs are libvirt's, Cloud Hypervisor's or Proxmox's",
            },
            C::MetricsPrometheus => S::Supported {
                evidence: "e2e:métricas: /metrics expõe gauges por container (cpu/mem)",
            },
            C::MetricsPerWorkloadNetwork => S::Supported {
                evidence: "e2e:métricas: /metrics expõe rx/tx de rede por container",
            },
            C::HostHealth => S::Supported {
                evidence: "check:system info",
            },
            // `node::capacity()` (served at `/v1/node/capacity`, ADR-0042 step
            // C): CPUs, memory, pids and the state/images/volumes/vm-images
            // filesystems. `*_total` is the HOST's; `*_allocatable` is what THIS
            // engine can actually enforce — read from the delegated cgroup slice
            // (`cpu.max`, `memory.max`, `pids.max`), so under rootless it is the
            // room the delegated subtree grants, not the whole machine. A number
            // that could not be measured goes into `unmeasured` and is never
            // reported as a silent zero.
            C::HostCapacity => S::Supported {
                evidence:
                    "check:GET /v1/node/capacity: cada número é medido ou está em unmeasured, nunca um zero calado",
            },
            C::TransportVerified => S::Partial {
                detail: "the control transports (CRI, management, docker-api) are unix sockets with SO_PEERCRED, owned by the engine's uid; the only TCP bound is the CRI streaming server on loopback (127.0.0.1, for exec/attach/port-forward), never 0.0.0.0 — local-only, but a named battery and a decision on whether the loopback streamer counts are pending",
            },
            C::CredentialInVault => S::Supported {
                evidence: "e2e:access: a --secret is injected from the vault at spawn but never persisted in the container record (credential in vault)",
            },
            C::NetBridge
            | C::NetMacvlanIpvlan
            | C::NetVlan
            | C::NetOverlayVxlan
            | C::NetOverlayEncrypted
            | C::NetIpam
            | C::NetStaticIp
            | C::NetDns
            | C::NetPublishPorts
            | C::NetRoutesBetweenNetworks
            | C::NetNamespaceIsolation
            | C::NetL7Proxy
            | C::NetTunnelEgress
            | C::NetIpv6
            | C::NetRateLimit
            | C::NetPacketCapture
            | C::FirewallPerWorkload
            | C::FirewallDefaultDeny
            | C::FirewallSourceFiltering
            | C::FirewallEgressPolicy
            | C::NetGatewayFilter
            | C::NetGatewayAlias
            | C::NetGatewayUpdateInPlace
            | C::NetGatewayRuleOrder
            | C::NetGatewayMultiWan
            | C::NetGatewayVpn
            | C::NetNatSnat
            | C::NetNatDnat
            | C::NetNatOneToOne
            | C::NetNatNpt
            | C::NetLbL4
            | C::NetLbHealthCheck
            | C::NetDnsRecords
            | C::NetDnsAuthoritative
            | C::NetIpamProvider
            | C::NetIpamReservation
            | C::NetIpamDhcp
            | C::NetSegmentRemote
            | C::NetApplyStaged
            | C::NetApplyRollback
            | C::NetObserve
            | C::NetVerifyDataplane
            | C::NetOwnershipMarker
            | C::FirewallStateless
            | C::FirewallLogging
            | C::FirewallIcmpType
            | C::FirewallWorkloadPeer
            | C::FirewallIntraSegment
            | C::VolumeLocal
            | C::VolumeBind
            | C::VolumeNfs
            | C::VolumeCifs
            | C::VolumeWebdav
            | C::VolumeQuota
            | C::VolumeSnapshot
            | C::VolumeProvisionNas
            | C::StorageLvmThin
            | C::StorageZfsBtrfs
            | C::StorageCeph => S::UnsupportedByProvider {
                reason: "not a compute capability: answered by the network/storage provider",
            },
        }
        },
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn without_delegation_limits_read_as_unavailable_not_as_supported() {
        let host = LinuxHost {
            cgroup_delegated: false,
            ..LinuxHost::ASSUMED
        };
        let r = report(&host);
        assert_eq!(r.health.reason, "CgroupNotDelegated");
        let lim = r
            .capabilities
            .iter()
            .find(|x| x.capability == C::ContainerResourceLimits)
            .unwrap();
        assert_eq!(lim.state.label(), "unavailable-on-host");
        let exec = r
            .capabilities
            .iter()
            .find(|x| x.capability == C::ContainerExec)
            .unwrap();
        assert_eq!(exec.state.label(), "supported");
    }
}
